#include <unistd.h>

void	ft_is_negative(int n)
{
	char	a;
	char	p;

	a = 'N';
	p = 'P';
	if (n <= -1)
	{
		write(1, &a, 1);
	}
	else
	{
		write(1, &p, 1);
	}
}
